import fs from 'node:fs';
import crypto from 'node:crypto';
const path='site/tailwind.generated.css';
const css=fs.readFileSync(path,'utf8');
if(!css.includes('.bg-obsidian')||!css.includes('.text-gold')||css.length<18000)throw new Error('Tailwind CSS generation incomplete: '+css.length);
const hash=crypto.createHash('sha256').update(css).digest('hex').slice(0,12);
fs.writeFileSync('site/src/tailwind.mjs','// Generated by official Tailwind CLI from approved reference. sha256 '+hash+'\nexport const TAILWIND_CSS = '+JSON.stringify(css)+';\n');
console.log('Tailwind '+css.length+' bytes, digest '+hash);
