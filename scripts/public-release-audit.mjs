#!/usr/bin/env node
// Public repository hygiene: check tracked files; never print matched secret values.
import {execFileSync} from 'node:child_process';
import {readFileSync} from 'node:fs';
import {extname} from 'node:path';

const strict = process.argv.includes('--strict-compiled-only');
const checkedExtensions = new Set(['.md','.mjs','.js','.cjs','.json','.jsonc','.yml','.yaml','.toml','.sql','.html','.css','.ps1','.txt','.svg','.mq5']);
const blockedPaths = [
  /^AGENTS\.md$/i, /^CLAUDE\.md$/i, /^GEMINI\.md$/i,
  /^\.cursor\//i, /^\.claude\//i, /^\.codex\//i, /^\.aider/i,
  /(?:^|\/)\.prompt\.md$/i, /(?:^|\/)copilot-instructions\.md$/i
];
const fingerprints = [
  ['private key header', /-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----/],
  ['GitHub access token', /gh[pousr]_[A-Za-z0-9_]{20,}/],
  ['OpenAI-format access token', /sk-(?:proj-)?[A-Za-z0-9_-]{32,}/],
  ['AWS access key', /AKIA[0-9A-Z]{16}/],
  ['Telegram bot token', /(?:^|[^0-9])[0-9]{8,12}:[A-Za-z0-9_-]{35,}(?:$|[^A-Za-z0-9_-])/],
  ['literal assistant attribution', /\b(?:Co-authored-by:\s*(?:Claude|ChatGPT|Codex|Copilot)|generated by (?:Claude|ChatGPT|Codex|Copilot))\b/i]
];
const exclusions = new Set(['scripts/public-release-audit.mjs']); // The scanner necessarily contains signature literals.
let paths;
try { paths = execFileSync('git',['ls-files','-z'],{encoding:'utf8'}).split('\0').filter(Boolean); }
catch { console.error('Public audit requires a Git checkout; refusing to claim a pass.'); process.exit(2); }
let failures = 0, scanned = 0;
for (const path of paths) {
  if (blockedPaths.some(re=>re.test(path))) { console.error(`BLOCKED development-assistant manifest: ${path}`); failures++; }
  if (strict && /^mt5\/.*\.mq5$/i.test(path)) { console.error(`Compiled-only distribution blocked by tracked source: ${path}`); failures++; }
  if (!checkedExtensions.has(extname(path).toLowerCase()) || exclusions.has(path)) continue;
  let value;
  try { value=readFileSync(path,'utf8'); } catch { console.error(`Could not inspect tracked file: ${path}`); failures++; continue; }
  scanned++;
  for (const [label,re] of fingerprints) if (re.test(value)) { console.error(`Potential ${label}: ${path} (value withheld)`); failures++; }
}
if (!strict && paths.some(p=>/^mt5\/.*\.mq5$/i.test(p))) {
  console.warn('NOTICE: proprietary MQL5 source remains publicly tracked; the compiled-only release gate is NOT cleared.');
}
console.log(`Public audit inspected ${scanned} text files; ${failures} blocking finding(s).`);
process.exitCode = failures ? 1 : 0;
